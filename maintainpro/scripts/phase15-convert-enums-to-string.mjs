/**
 * Phase 15 — convert Prisma enums → String for SQL Server (Prisma 5 has no SQL Server enums).
 * Writes apps/api/src/database/prisma-enums.ts and patches schema.prisma.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(root, "prisma", "schema.prisma");
const enumsOut = path.join(root, "apps", "api", "src", "database", "prisma-enums.ts");

let schema = fs.readFileSync(schemaPath, "utf8");

const enumBlocks = [...schema.matchAll(/^enum\s+(\w+)\s*\{([^}]*)\}/gm)];
const enumNames = enumBlocks.map((m) => m[1]);
console.log("enums found:", enumNames.length);

const tsLines = [
  "/**",
  " * Phase 15 — TypeScript enums formerly generated by Prisma Client.",
  " * SQL Server Prisma connector does not support native enums; schema stores String.",
  " * Keep values identical to pre-migration Prisma enums.",
  " */",
  "",
];

for (const m of enumBlocks) {
  const name = m[1];
  const body = m[2]
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("//") && !l.startsWith("@@"));
  tsLines.push(`export enum ${name} {`);
  for (const v of body) {
    const mem = v.replace(/,.*/, "").trim();
    if (!mem) continue;
    tsLines.push(`  ${mem} = "${mem}",`);
  }
  tsLines.push(`}`);
  tsLines.push("");
}

fs.mkdirSync(path.dirname(enumsOut), { recursive: true });
fs.writeFileSync(enumsOut, tsLines.join("\n"));
console.log("wrote", enumsOut);

// Remove enum blocks from schema
schema = schema.replace(/^enum\s+\w+\s*\{[^}]*\}\s*/gm, "");

// Replace enum type usages in fields with String @db.NVarChar(64)
// Avoid replacing inside comments where possible by only matching field lines.
for (const name of enumNames.sort((a, b) => b.length - a.length)) {
  // field EnumName? or field EnumName @default(...)
  const re = new RegExp(
    `(\\n\\s+\\w+\\s+)${name}(\\?)?(\\s+@default\\([^)]+\\))?`,
    "g"
  );
  schema = schema.replace(re, (_, pre, opt, def) => {
    const optional = opt || "";
    const defaultPart = def || "";
    return `${pre}String${optional}${defaultPart} @db.NVarChar(64)`;
  });
}

// Collapse duplicate @db.NVarChar
schema = schema.replace(/@db\.NVarChar\(64\)\s+@db\.NVarChar\(64\)/g, "@db.NVarChar(64)");
schema = schema.replace(/@db\.NVarChar\(Max\)\s+@db\.NVarChar\(64\)/g, "@db.NVarChar(Max)");
schema = schema.replace(/@db\.NVarChar\(64\)\s+@db\.NVarChar\(Max\)/g, "@db.NVarChar(Max)");

fs.writeFileSync(schemaPath, schema);
console.log("schema enums converted to String");
