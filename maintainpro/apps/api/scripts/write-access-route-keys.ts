import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { planAccessRouteKeys, type AccessPlanRoute } from "../src/common/auth/access-route-plan";

const apiRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(apiRoot, "../..");
const inventoryPath = path.resolve(repoRoot, "docs/handover/access/route-inventory.json");
const planPath = path.resolve(repoRoot, "docs/handover/access/route-key-plan.json");
const dataPath = path.resolve(apiRoot, "src/common/auth/access-route-key-data.ts");
const runtimeInventoryPath = path.resolve(apiRoot, "src/database/access-route-inventory.json");

type InventoryRoute = AccessPlanRoute & {
  permissions?: string[];
  isPublic?: boolean;
};

const inventory = JSON.parse(readFileSync(inventoryPath, "utf8")) as { routes: InventoryRoute[] };
const plan = planAccessRouteKeys(inventory.routes);
const routeKeys: Record<string, string> = {};
for (const route of plan.routes) {
  routeKeys[`${route.method} ${route.path}`] = route.key;
}
const grants: Record<string, string[]> = {};
for (const entry of plan.keys) {
  grants[entry.key] = entry.roles;
}

const data = `/** Generated by apps/api/scripts/write-access-route-keys.ts. Do not edit by hand. */
export const ACCESS_ROUTE_KEYS: Readonly<Record<string, string>> = ${JSON.stringify(routeKeys, null, 2)};

export const ACCESS_KEY_CATALOG: readonly { key: string; label: string; module: string }[] = ${JSON.stringify(
  plan.keys.map(({ key, label, module }) => ({ key, label, module })),
  null,
  2
)};

export const ACCESS_STUDIO_ROUTE_GRANTS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(grants, null, 2)};
`;

mkdirSync(path.dirname(dataPath), { recursive: true });
mkdirSync(path.dirname(planPath), { recursive: true });
writeFileSync(dataPath, data);
writeFileSync(planPath, `${JSON.stringify(plan, null, 2)}\n`);

const runtimeRoutes = inventory.routes.map((route) => ({
  method: route.method,
  path: route.path,
  roles: route.roles,
  permissions: route.permissions ?? [],
  isPublic: route.isPublic === true
}));
writeFileSync(runtimeInventoryPath, `${JSON.stringify({ routes: runtimeRoutes })}\n`);

const keyCount = plan.keyCount;
if (keyCount < 110 || keyCount > 210) {
  throw new Error(`Expected 110-210 access keys, got ${keyCount}`);
}
console.log(`keys=${keyCount} routes=${plan.routeCount}`);
