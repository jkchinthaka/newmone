import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../src");

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.name.endsWith(".ts") && !entry.name.endsWith(".spec.ts")) files.push(full);
  }
  return files;
}

const files = walk(src).filter(
  (file) => file.endsWith(".controller.ts") || file.includes(`${path.sep}farm${path.sep}`)
);
const lines = [
  "/* Generated by scripts/access-route-inventory.mjs so Jest can read decorator metadata. */"
];
files.forEach((file, index) => {
  const rel = path.relative(path.join(here, "../test"), file).replaceAll("\\", "/").replace(/\.ts$/, "");
  const names = [...readFileSync(file, "utf8").matchAll(/export class (\w+)/g)].map((match) => match[1]);
  names.forEach((name, nameIndex) => {
    lines.push(`export { ${name} as Inventory${index}_${nameIndex} } from "${rel}";`);
  });
});
const out = path.resolve(here, "../test/access-inventory-barrel.ts");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`exports=${lines.length - 1}`);
