import { existsSync } from "node:fs";
import path from "node:path";

import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";

export const NERS_GREEN = "#216E39";
export const NERS_GOLD = "#D9AC36";
export const NERS_TEXT = "#233044";
export const NERS_TIMEZONE = "Asia/Colombo";
export const NELNA_LEGAL_NAME = "Nelna Farm (Pvt) Ltd";

export type NersColumn = { key: string; label: string; type?: string };
export type NersRow = Record<string, string | number | null>;

export type NersDocument = {
  title: string;
  organizationName: string;
  generatedAt: Date;
  generatedBy?: string | null;
  period?: string | null;
  filters: Array<{ label: string; value: string }>;
  kpis: Array<{ label: string; value: string }>;
  columns: NersColumn[];
  rows: NersRow[];
  coverageNotes: string[];
  truncatedNote?: string | null;
  logoPath?: string | null;
};

export function isNelnaOrganization(name: string | null | undefined) {
  return /nelna/i.test(name ?? "") || !String(name ?? "").trim();
}

export function colomboStamp(value: Date) {
  return new Intl.DateTimeFormat("en-GB", {
    timeZone: NERS_TIMEZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23"
  }).format(value);
}

export function nersFilename(title: string, extension: "pdf" | "xlsx" | "csv", when = new Date()) {
  const slug = title.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").slice(0, 48) || "Report";
  const day = new Intl.DateTimeFormat("en-CA", { timeZone: NERS_TIMEZONE, year: "numeric", month: "2-digit", day: "2-digit" }).format(when);
  return `NELNA_${slug}_${day}.${extension}`;
}

export function officialLogoPath() {
  const candidates = [
    path.join(process.cwd(), "assets", "brand", "nelna-group-logo.jpg"),
    path.join(process.cwd(), "apps", "api", "assets", "brand", "nelna-group-logo.jpg")
  ];
  return candidates.find((candidate) => existsSync(candidate)) ?? null;
}

function cellText(value: string | number | null | undefined) {
  if (value == null || value === "") return "—";
  return String(value);
}

export function renderNersPdf(input: NersDocument): Promise<Buffer> {
  const logo = input.logoPath && existsSync(input.logoPath) && isNelnaOrganization(input.organizationName) ? input.logoPath : null;
  const layout = input.columns.length > 6 ? "landscape" : "portrait";
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", layout, margin: 36, bufferPages: true, compress: false });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const drawHeader = () => {
      const top = 36;
      if (logo) doc.image(logo, 36, top, { width: 72 });
      doc.fillColor(NERS_TEXT).fontSize(11).text(input.organizationName || NELNA_LEGAL_NAME, 120, top, { align: "right" });
      doc.fontSize(9).fillColor(NERS_GREEN).text("MaintainPro", { align: "right" });
      doc.fillColor(NERS_TEXT).fontSize(8).text("Enterprise Operations", { align: "right" });
      const lineY = logo ? 118 : 78;
      doc.moveTo(36, lineY).lineTo(doc.page.width - 36, lineY).lineWidth(2).strokeColor(NERS_GREEN).stroke();
      doc.y = lineY + 12;
      doc.fillColor(NERS_TEXT).fontSize(16).text(input.title);
      doc.moveDown(0.2);
      doc.fontSize(8).fillColor("#475569");
      doc.text(`Generated ${colomboStamp(input.generatedAt)} (${NERS_TIMEZONE})`);
      if (input.period) doc.text(`Period ${input.period}`);
      if (input.generatedBy) doc.text(`Generated by ${input.generatedBy}`);
      const filterLine = input.filters.filter((item) => item.value).map((item) => `${item.label}: ${item.value}`).join(" · ");
      if (filterLine) doc.text(filterLine, { width: doc.page.width - 72 });
      doc.moveDown(0.4);
    };

    drawHeader();
    if (input.kpis.length > 0) {
      doc.fontSize(9).fillColor(NERS_TEXT);
      doc.text(input.kpis.map((card) => `${card.label}: ${card.value}`).join("    "), { width: doc.page.width - 72 });
      doc.moveDown(0.4);
    }

    const columns = input.columns;
    const tableWidth = doc.page.width - 72;
    const widths = columns.map(() => tableWidth / Math.max(columns.length, 1));
    const drawHeadings = () => {
      const y = doc.y;
      doc.rect(36, y, tableWidth, 16).fill(NERS_GREEN);
      doc.fillColor("#FFFFFF").fontSize(8);
      columns.forEach((column, index) => {
        const x = 36 + widths.slice(0, index).reduce((sum, item) => sum + item, 0);
        doc.text(column.label, x + 2, y + 4, { width: widths[index] - 4, ellipsis: true });
      });
      doc.y = y + 18;
      doc.fillColor(NERS_TEXT);
    };
    if (columns.length > 0) drawHeadings();

    input.rows.forEach((row, rowIndex) => {
      const heights = columns.map((column, index) =>
        doc.heightOfString(cellText(row[column.key]), { width: widths[index] - 4 })
      );
      const rowHeight = Math.max(14, ...heights) + 4;
      if (doc.y + rowHeight > doc.page.height - 48) {
        doc.addPage();
        drawHeader();
        drawHeadings();
      }
      const y = doc.y;
      if (rowIndex % 2 === 1) doc.rect(36, y, tableWidth, rowHeight).fill("#F1F5F2");
      doc.fillColor(NERS_TEXT).fontSize(8);
      columns.forEach((column, index) => {
        const x = 36 + widths.slice(0, index).reduce((sum, item) => sum + item, 0);
        const align = column.type === "number" || column.type === "currency" ? "right" : "left";
        doc.text(cellText(row[column.key]), x + 2, y + 2, { width: widths[index] - 4, align });
      });
      doc.y = y + rowHeight;
    });

    doc.moveDown(0.6);
    doc.fontSize(8).fillColor("#475569");
    for (const note of [...input.coverageNotes, input.truncatedNote].filter(Boolean) as string[]) {
      doc.text(note, { width: doc.page.width - 72 });
    }
    doc.moveDown(0.4);
    doc.fillColor(NERS_TEXT).text(`${input.organizationName || NELNA_LEGAL_NAME} · Generated by MaintainPro`);

    const range = doc.bufferedPageRange();
    for (let index = 0; index < range.count; index += 1) {
      doc.switchToPage(index);
      doc.fontSize(8).fillColor("#475569").text(`Page ${index + 1} of ${range.count}`, 36, doc.page.height - 28, {
        align: "right",
        width: doc.page.width - 72
      });
    }
    doc.end();
  });
}

export async function renderNersWorkbook(input: NersDocument): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "MaintainPro";
  workbook.created = input.generatedAt;
  const summary = workbook.addWorksheet("Summary");
  const logo = input.logoPath && existsSync(input.logoPath) && isNelnaOrganization(input.organizationName) ? input.logoPath : null;
  let row = 1;
  if (logo) {
    const imageId = workbook.addImage({ filename: logo, extension: "jpeg" });
    summary.addImage(imageId, { tl: { col: 0, row: 0 }, ext: { width: 96, height: 74 } });
    row = 6;
  }
  summary.getCell(`A${row}`).value = input.organizationName || NELNA_LEGAL_NAME;
  summary.getCell(`A${row}`).font = { bold: true, color: { argb: "FF216E39" }, size: 14 };
  summary.getCell(`A${row + 1}`).value = "MaintainPro";
  summary.getCell(`A${row + 2}`).value = input.title;
  summary.getCell(`A${row + 2}`).font = { bold: true, size: 16 };
  summary.getCell(`A${row + 3}`).value = `Generated ${colomboStamp(input.generatedAt)} ${NERS_TIMEZONE}`;
  if (input.period) summary.getCell(`A${row + 4}`).value = `Period ${input.period}`;
  if (input.generatedBy) summary.getCell(`A${row + 5}`).value = `Generated by ${input.generatedBy}`;
  let kpiRow = row + 7;
  for (const card of input.kpis) {
    summary.getCell(`A${kpiRow}`).value = card.label;
    summary.getCell(`B${kpiRow}`).value = card.value;
    kpiRow += 1;
  }
  for (const note of input.coverageNotes) {
    summary.getCell(`A${kpiRow}`).value = note;
    kpiRow += 1;
  }
  summary.getColumn(1).width = 42;
  summary.getColumn(2).width = 28;
  summary.pageSetup = { paperSize: 9, orientation: input.columns.length > 6 ? "landscape" : "portrait", fitToPage: true, fitToWidth: 1 };

  const data = workbook.addWorksheet("Data");
  data.columns = input.columns.map((column) => ({ header: column.label, key: column.key, width: Math.max(16, column.label.length + 2) }));
  for (const source of input.rows) {
    const record: Record<string, string | number | Date | null> = {};
    for (const column of input.columns) {
      const value = source[column.key];
      if (column.type === "number" || column.type === "currency") {
        const numeric = typeof value === "number" ? value : Number(value);
        record[column.key] = Number.isFinite(numeric) ? numeric : null;
      } else {
        const text = value == null ? "" : String(value);
        record[column.key] = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
      }
    }
    data.addRow(record);
  }
  data.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
  data.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF216E39" } };
  data.views = [{ state: "frozen", ySplit: 1 }];
  data.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: Math.max(input.columns.length, 1) } };
  data.pageSetup = { paperSize: 9, orientation: "landscape", fitToPage: true, fitToWidth: 1 };
  input.columns.forEach((column, index) => {
    if (column.type === "currency") data.getColumn(index + 1).numFmt = '"LKR" #,##0.00';
    if (column.type === "number") data.getColumn(index + 1).numFmt = "#,##0.00";
  });

  const info = workbook.addWorksheet("Filters");
  info.addRow(["Field", "Value"]);
  info.addRow(["Organization", input.organizationName || NELNA_LEGAL_NAME]);
  info.addRow(["Report", input.title]);
  info.addRow(["Generated", colomboStamp(input.generatedAt)]);
  info.addRow(["Generated by", input.generatedBy ?? ""]);
  info.addRow(["Period", input.period ?? ""]);
  for (const filter of input.filters) info.addRow([filter.label, filter.value]);
  if (input.truncatedNote) info.addRow(["Coverage", input.truncatedNote]);
  for (const note of input.coverageNotes) info.addRow(["Note", note]);
  info.getRow(1).font = { bold: true };
  info.getColumn(1).width = 28;
  info.getColumn(2).width = 64;
  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}
